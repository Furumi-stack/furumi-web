def words(text):
    return re.findall(r"[^\W_]+", text.lower().replace("ё", "е"))


def main(source, output, cases):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != "3f6e43fb066916f3ee32dd7b63488c4831b62a29f72caa41e806a8ef59749c89":
        raise ValueError("Expected the PoetryCorpus all.xml snapshot documented in this script")
    authors = {author for author, *_ in cases}
    poems = {}
    for item in ET.fromstring(raw):
        author = item.findtext("author").split()[-1]
        if author in authors:
            poems[author, item.findtext("name")] = item.findtext("text").strip()

    docs = {}
    for author, title, short, long in cases:
        text = poems[author, title]
        tokens = words(text)
        start = len(tokens) // 3
        docs[" ".join(tokens)] = {
            "text": text,
            "queries": {
                "short_quote": " ".join(tokens[start:start + 3]),
                "long_quote": " ".join(tokens[start:start + 11]),
                "short_paraphrase": short,
                "long_paraphrase": long,
            },
        }
    # Keep competitors by the same authors and deduplicate alternate editions.
    for text in sorted(poems.values(), key=lambda s: hashlib.sha256(s.encode()).digest()):
        if 200 <= len(text) <= 2000:
            docs.setdefault(" ".join(words(text)), {"text": text, "queries": {}})
        if len(docs) == 256:
            break
    output.write_text(json.dumps(list(docs.values()), ensure_ascii=False), encoding="utf-8")


